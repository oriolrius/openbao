// Route tests for transit/session-key/pkcs1v15/:name (PKI Manager downstream).
// Fixtures: fresh RSA-3072 keys generated by Transit or by the test, session
// keys from crypto/rand, ciphertexts from crypto/rsa.EncryptPKCS1v15.

func skWrite(t *testing.T, b *backend, s logical.Storage, path string, data map[string]any) (*logical.Response, error) {
	t.Helper()
	return b.HandleRequest(t.Context(), &logical.Request{
		Storage:   s,
		Operation: logical.UpdateOperation,
		Path:      path,
		Data:      data,
	})
}

func skRead(t *testing.T, b *backend, s logical.Storage, path string) *logical.Response {
	t.Helper()
	resp, err := b.HandleRequest(t.Context(), &logical.Request{
		Storage:   s,
		Operation: logical.ReadOperation,
		Path:      path,
	})
	require.NoError(t, err)
	require.NotNil(t, resp)
	require.False(t, resp.IsError(), "read %s: %v", path, resp.Error())
	return resp
}

func skPublicKey(t *testing.T, b *backend, s logical.Storage, name string, version int) *rsa.PublicKey {
	t.Helper()
	resp := skRead(t, b, s, "keys/"+name)
	keys := resp.Data["keys"].(map[string]map[string]any)
	entry, ok := keys[strconv.Itoa(version)]
	require.True(t, ok, "no key version %d", version)
	block, _ := pem.Decode([]byte(entry["public_key"].(string)))
	require.NotNil(t, block)
	pub, err := x509.ParsePKIXPublicKey(block.Bytes)
	require.NoError(t, err)
	return pub.(*rsa.PublicKey)
}

func skEncrypt(t *testing.T, pub *rsa.PublicKey, keyLen int) (sessionKey []byte, ciphertextB64 string) {
	t.Helper()
	sessionKey = make([]byte, keyLen)
	_, err := rand.Read(sessionKey)
	require.NoError(t, err)
	ciphertext, err := rsa.EncryptPKCS1v15(rand.Reader, pub, sessionKey)
	require.NoError(t, err)
	return sessionKey, base64.StdEncoding.EncodeToString(ciphertext)
}

func skUnwrap(t *testing.T, b *backend, s logical.Storage, name string, version int, ciphertext string, keyLen int) (*logical.Response, error) {
	t.Helper()
	return skWrite(t, b, s, "session-key/pkcs1v15/"+name, map[string]any{
		"ciphertext":         ciphertext,
		"key_version":        version,
		"session_key_length": keyLen,
	})
}

func requireSessionKey(t *testing.T, resp *logical.Response, err error, want []byte) {
	t.Helper()
	require.NoError(t, err)
	require.NotNil(t, resp)
	require.False(t, resp.IsError(), "unexpected error: %v", resp.Error())
	got, decErr := base64.StdEncoding.DecodeString(resp.Data["session_key"].(string))
	require.NoError(t, decErr)
	require.Equal(t, want, got)
}

func requireRequestError(t *testing.T, resp *logical.Response, err error, contains string) {
	t.Helper()
	require.ErrorIs(t, err, logical.ErrInvalidRequest)
	require.NotNil(t, resp)
	require.True(t, resp.IsError())
	require.Contains(t, resp.Error().Error(), contains)
}

func TestTransit_PKCS1v15SessionKey_Route(t *testing.T) {
	b, s := createBackendWithStorage(t)

	resp, err := skWrite(t, b, s, "keys/scep-ra", map[string]any{
		"type":                       "rsa-3072",
		"allow_pkcs1v15_session_key": true,
	})
	require.NoError(t, err)
	require.False(t, resp.IsError())
	require.Equal(t, true, resp.Data["allow_pkcs1v15_session_key"])
	require.Equal(t, false, resp.Data["exportable"])

	_, err = skWrite(t, b, s, "keys/plain-rsa", map[string]any{"type": "rsa-3072"})
	require.NoError(t, err)
	require.Equal(t, false, skRead(t, b, s, "keys/plain-rsa").Data["allow_pkcs1v15_session_key"])

	pub1 := skPublicKey(t, b, s, "scep-ra", 1)
	require.Equal(t, 384, pub1.Size())

	t.Run("recovers each accepted length", func(t *testing.T) {
		for _, keyLen := range []int{16, 24, 32} {
			want, ciphertext := skEncrypt(t, pub1, keyLen)
			resp, err := skUnwrap(t, b, s, "scep-ra", 1, ciphertext, keyLen)
			requireSessionKey(t, resp, err, want)
			require.Equal(t, 1, resp.Data["key_version"])
		}
	})

	t.Run("wrong expected length returns a stable fallback, not an error", func(t *testing.T) {
		want, ciphertext := skEncrypt(t, pub1, 16)
		first, err := skUnwrap(t, b, s, "scep-ra", 1, ciphertext, 32)
		require.NoError(t, err)
		require.False(t, first.IsError())
		second, err := skUnwrap(t, b, s, "scep-ra", 1, ciphertext, 32)
		require.NoError(t, err)
		require.Equal(t, first.Data["session_key"], second.Data["session_key"])
		got, _ := base64.StdEncoding.DecodeString(first.Data["session_key"].(string))
		require.Len(t, got, 32)
		require.False(t, bytes.HasPrefix(got, want))
	})

	t.Run("request validation", func(t *testing.T) {
		_, ciphertext := skEncrypt(t, pub1, 16)
		raw, _ := base64.StdEncoding.DecodeString(ciphertext)

		resp, err := skWrite(t, b, s, "session-key/pkcs1v15/scep-ra", map[string]any{"ciphertext": ciphertext, "session_key_length": 16})
		requireRequestError(t, resp, err, `"key_version"`)
		resp, err = skWrite(t, b, s, "session-key/pkcs1v15/scep-ra", map[string]any{"ciphertext": ciphertext, "key_version": 1})
		requireRequestError(t, resp, err, `"session_key_length"`)
		resp, err = skWrite(t, b, s, "session-key/pkcs1v15/scep-ra", map[string]any{"key_version": 1, "session_key_length": 16})
		requireRequestError(t, resp, err, `"ciphertext"`)
		resp, err = skWrite(t, b, s, "session-key/pkcs1v15/scep-ra", map[string]any{
			"key_version": 1, "session_key_length": 16, "ciphertext": ciphertext,
			"batch_input": []any{map[string]any{"ciphertext": ciphertext}},
		})
		requireRequestError(t, resp, err, "batch_input")

		for _, n := range []int{0, 8, 20, 48, 64} {
			resp, err = skUnwrap(t, b, s, "scep-ra", 1, ciphertext, n)
			requireRequestError(t, resp, err, "session_key_length")
		}
		resp, err = skUnwrap(t, b, s, "scep-ra", 1, "not base64!", 16)
		requireRequestError(t, resp, err, "base64")
		resp, err = skUnwrap(t, b, s, "scep-ra", 1, base64.StdEncoding.EncodeToString(raw[:256]), 16)
		requireRequestError(t, resp, err, "exactly 384 bytes")
		resp, err = skUnwrap(t, b, s, "scep-ra", 0, ciphertext, 16)
		requireRequestError(t, resp, err, "version")
		resp, err = skUnwrap(t, b, s, "scep-ra", 2, ciphertext, 16)
		requireRequestError(t, resp, err, "version")
		resp, err = skUnwrap(t, b, s, "missing", 1, ciphertext, 16)
		requireRequestError(t, resp, err, "not found")
	})

	t.Run("keys without the opt-in are refused", func(t *testing.T) {
		pub := skPublicKey(t, b, s, "plain-rsa", 1)
		_, ciphertext := skEncrypt(t, pub, 16)
		resp, err := skUnwrap(t, b, s, "plain-rsa", 1, ciphertext, 16)
		requireRequestError(t, resp, err, "does not permit")

		// Upsert of an existing key does not add the opt-in.
		resp, err = skWrite(t, b, s, "keys/plain-rsa", map[string]any{"type": "rsa-3072", "allow_pkcs1v15_session_key": true})
		require.NoError(t, err)
		require.Contains(t, strings.Join(resp.Warnings, " "), "allow_pkcs1v15_session_key applies only to a new key")
		resp, err = skUnwrap(t, b, s, "plain-rsa", 1, ciphertext, 16)
		requireRequestError(t, resp, err, "does not permit")

		// keys/config does not know the field.
		resp, err = skWrite(t, b, s, "keys/plain-rsa/config", map[string]any{"allow_pkcs1v15_session_key": true})
		require.NoError(t, err)
		resp, err = skUnwrap(t, b, s, "plain-rsa", 1, ciphertext, 16)
		requireRequestError(t, resp, err, "does not permit")
	})

	t.Run("opt-in requires rsa-3072", func(t *testing.T) {
		for _, keyType := range []string{"rsa-2048", "rsa-4096", "aes256-gcm96", "ecdsa-p256"} {
			resp, err := skWrite(t, b, s, "keys/bad-"+keyType, map[string]any{"type": keyType, "allow_pkcs1v15_session_key": true})
			requireRequestError(t, resp, err, "requires type rsa-3072")
			require.Nil(t, skReadMaybe(t, b, s, "keys/bad-"+keyType), "key %s was created", keyType)
		}
	})

	t.Run("OAEP decrypt and signing keep working on the opted-in key", func(t *testing.T) {
		plaintext := base64.StdEncoding.EncodeToString([]byte("oaep regression"))
		resp, err := skWrite(t, b, s, "encrypt/scep-ra", map[string]any{"plaintext": plaintext})
		require.NoError(t, err)
		resp, err = skWrite(t, b, s, "decrypt/scep-ra", map[string]any{"ciphertext": resp.Data["ciphertext"]})
		require.NoError(t, err)
		require.Equal(t, plaintext, resp.Data["plaintext"])

		// decrypt/ stays OAEP-only: a PKCS#1 v1.5 ciphertext fails there.
		_, ciphertext := skEncrypt(t, pub1, 16)
		_, err = skWrite(t, b, s, "decrypt/scep-ra", map[string]any{"ciphertext": "vault:v1:" + ciphertext})
		require.Error(t, err)

		resp, err = skWrite(t, b, s, "sign/scep-ra/sha2-256", map[string]any{
			"input": base64.StdEncoding.EncodeToString([]byte("ra message")), "signature_algorithm": "pkcs1v15",
		})
		require.NoError(t, err)
		require.True(t, strings.HasPrefix(resp.Data["signature"].(string), "vault:v1:"))
	})

	t.Run("non-exportable identity stays non-exportable", func(t *testing.T) {
		for _, path := range []string{"export/encryption-key/scep-ra", "export/public-key/scep-ra/1", "backup/scep-ra"} {
			resp, err := b.HandleRequest(t.Context(), &logical.Request{
				Storage: s, Operation: logical.ReadOperation, Path: path,
			})
			if path == "export/public-key/scep-ra/1" {
				// The public key stays readable; only private material is refused.
				require.NoError(t, err)
				require.False(t, resp.IsError())
				continue
			}
			require.True(t, err != nil || (resp != nil && resp.IsError()), "%s was not refused", path)
		}
	})

	t.Run("version lifecycle", func(t *testing.T) {
		v1Key, v1Ciphertext := skEncrypt(t, pub1, 32)
		resp, err := skWrite(t, b, s, "keys/scep-ra/rotate", nil)
		require.NoError(t, err)
		require.False(t, resp.IsError())
		require.Equal(t, true, skRead(t, b, s, "keys/scep-ra").Data["allow_pkcs1v15_session_key"], "rotation keeps the opt-in")

		pub2 := skPublicKey(t, b, s, "scep-ra", 2)
		v2Key, v2Ciphertext := skEncrypt(t, pub2, 32)
		resp, err = skUnwrap(t, b, s, "scep-ra", 2, v2Ciphertext, 32)
		requireSessionKey(t, resp, err, v2Key)
		resp, err = skUnwrap(t, b, s, "scep-ra", 1, v1Ciphertext, 32)
		requireSessionKey(t, resp, err, v1Key)

		// No implicit version: v1 ciphertext with v2 yields a fallback.
		resp, err = skUnwrap(t, b, s, "scep-ra", 2, v1Ciphertext, 32)
		require.NoError(t, err)
		require.NotEqual(t, base64.StdEncoding.EncodeToString(v1Key), resp.Data["session_key"])

		resp, err = skWrite(t, b, s, "keys/scep-ra/config", map[string]any{"min_decryption_version": 2})
		require.NoError(t, err)
		require.False(t, resp.IsError())
		resp, err = skUnwrap(t, b, s, "scep-ra", 1, v1Ciphertext, 32)
		requireRequestError(t, resp, err, "too old")

		resp, err = b.HandleRequest(t.Context(), &logical.Request{
			Storage: s, Operation: logical.DeleteOperation, Path: "keys/scep-ra/soft-delete",
		})
		require.NoError(t, err)
		require.False(t, resp != nil && resp.IsError())
		resp, err = skUnwrap(t, b, s, "scep-ra", 2, v2Ciphertext, 32)
		requireRequestError(t, resp, err, "soft-deleted")
		_, err = skWrite(t, b, s, "keys/scep-ra/soft-delete-restore", nil)
		require.NoError(t, err)
		resp, err = skUnwrap(t, b, s, "scep-ra", 2, v2Ciphertext, 32)
		requireSessionKey(t, resp, err, v2Key)
	})
}

