// A migrated RA: an existing RSA-3072 private key imported with the opt-in.
func TestTransit_PKCS1v15SessionKey_ImportedRA(t *testing.T) {
	b, s := createBackendWithStorage(t)
	wrappingKey, err := b.getWrappingKey(t.Context(), s)
	require.NoError(t, err)
	pubWrappingKey := &wrappingKey.Keys[strconv.Itoa(wrappingKey.LatestVersion)].RSAKey.PublicKey

	raKey, err := rsa.GenerateKey(rand.Reader, 3072)
	require.NoError(t, err)
	blob := wrapTargetKeyForImport(t, pubWrappingKey, raKey, "rsa-3072", "SHA256")

	resp, err := skWrite(t, b, s, "keys/migrated-ra/import", map[string]any{
		"type": "rsa-3072", "ciphertext": blob, "allow_pkcs1v15_session_key": true,
	})
	require.NoError(t, err)
	require.False(t, resp != nil && resp.IsError())
	require.Equal(t, true, skRead(t, b, s, "keys/migrated-ra").Data["allow_pkcs1v15_session_key"])

	// The imported public identity is the original one.
	require.Equal(t, raKey.PublicKey.N, skPublicKey(t, b, s, "migrated-ra", 1).N)

	for _, keyLen := range []int{16, 24, 32} {
		want, ciphertext := skEncrypt(t, &raKey.PublicKey, keyLen)
		resp, err := skUnwrap(t, b, s, "migrated-ra", 1, ciphertext, keyLen)
		requireSessionKey(t, resp, err, want)
	}

	// Public-key-only import and other key types cannot opt in.
	spki, err := x509.MarshalPKIXPublicKey(&raKey.PublicKey)
	require.NoError(t, err)
	resp, err = skWrite(t, b, s, "keys/public-ra/import", map[string]any{
		"type": "rsa-3072", "public_key": string(pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: spki})),
		"allow_pkcs1v15_session_key": true,
	})
	requireRequestError(t, resp, err, "requires an imported private key")

	rsa2048, err := rsa.GenerateKey(rand.Reader, 2048)
	require.NoError(t, err)
	resp, err = skWrite(t, b, s, "keys/rsa2048-ra/import", map[string]any{
		"type": "rsa-2048", "ciphertext": wrapTargetKeyForImport(t, pubWrappingKey, rsa2048, "rsa-2048", "SHA256"),
		"allow_pkcs1v15_session_key": true,
	})
	requireRequestError(t, resp, err, "requires type rsa-3072")
}

// Route integration through the HTTP API: the ACL grants the RA identity
// only the session-key path of its key, and the audit log does not carry
// the ciphertext or the session key in clear.
func TestTransit_PKCS1v15SessionKey_ClusterACLAndAudit(t *testing.T) {
	coreConfig := &vault.CoreConfig{
		RawConfig:       &server.Config{UnsafeAllowAPIAuditCreation: true},
		LogicalBackends: map[string]logical.Factory{"transit": Factory},
		AuditBackends:   map[string]audit.Factory{"file": file.Factory},
	}
	cluster := vault.NewTestCluster(t, coreConfig, &vault.TestClusterOptions{HandlerFunc: vaulthttp.Handler})
	cluster.Start()
	defer cluster.Cleanup()
	vault.TestWaitActive(t, cluster.Cores[0].Core)
	root := cluster.Cores[0].Client

	auditPath := filepath.Join(t.TempDir(), "audit.log")
	require.NoError(t, root.Sys().EnableAuditWithOptions("file", &api.EnableAuditOptions{
		Type: "file", Options: map[string]string{"file_path": auditPath},
	}))
	require.NoError(t, root.Sys().Mount("transit", &api.MountInput{Type: "transit"}))

	_, err := root.Logical().Write("transit/keys/scep-ra-1", map[string]any{"type": "rsa-3072", "allow_pkcs1v15_session_key": true})
	require.NoError(t, err)
	_, err = root.Logical().Write("transit/keys/other-ra", map[string]any{"type": "rsa-3072", "allow_pkcs1v15_session_key": true})
	require.NoError(t, err)

	require.NoError(t, root.Sys().PutPolicy("scep-ra-runtime", `
path "transit/session-key/pkcs1v15/scep-ra-1" { capabilities = ["update"] }
path "transit/sign/scep-ra-1/*" { capabilities = ["update"] }
`))
	secret, err := root.Auth().Token().Create(&api.TokenCreateRequest{Policies: []string{"scep-ra-runtime"}, NoDefaultPolicy: true})
	require.NoError(t, err)
	ra, err := root.Clone()
	require.NoError(t, err)
	ra.SetToken(secret.Auth.ClientToken)

	keyResp, err := root.Logical().Read("transit/keys/scep-ra-1")
	require.NoError(t, err)
	block, _ := pem.Decode([]byte(keyResp.Data["keys"].(map[string]any)["1"].(map[string]any)["public_key"].(string)))
	require.NotNil(t, block)
	parsed, err := x509.ParsePKIXPublicKey(block.Bytes)
	require.NoError(t, err)
	pub := parsed.(*rsa.PublicKey)

	sessionKey, ciphertext := skEncrypt(t, pub, 32)
	resp, err := ra.Logical().Write("transit/session-key/pkcs1v15/scep-ra-1", map[string]any{
		"ciphertext": ciphertext, "key_version": 1, "session_key_length": 32,
	})
	require.NoError(t, err)
	sessionKeyB64 := base64.StdEncoding.EncodeToString(sessionKey)
	require.Equal(t, sessionKeyB64, resp.Data["session_key"])

	denied := map[string]map[string]any{
		"transit/session-key/pkcs1v15/other-ra": {"ciphertext": ciphertext, "key_version": 1, "session_key_length": 32},
		"transit/decrypt/scep-ra-1":             {"ciphertext": "vault:v1:" + ciphertext},
		"transit/keys/scep-ra-1/config":         {"exportable": true},
		"transit/keys/scep-ra-1/rotate":         {},
		"transit/keys/new-ra":                   {"type": "rsa-3072", "allow_pkcs1v15_session_key": true},
	}
	for path, data := range denied {
		_, err := ra.Logical().Write(path, data)
		require.Error(t, err, path)
		require.Contains(t, err.Error(), "permission denied", path)
	}
	for _, path := range []string{"transit/export/encryption-key/scep-ra-1", "transit/backup/scep-ra-1", "transit/keys/scep-ra-1"} {
		_, err := ra.Logical().Read(path)
		require.Error(t, err, path)
		require.Contains(t, err.Error(), "permission denied", path)
	}

	// Error responses never mention padding.
	_, err = ra.Logical().Write("transit/session-key/pkcs1v15/scep-ra-1", map[string]any{
		"ciphertext": base64.StdEncoding.EncodeToString(bytes.Repeat([]byte{1}, 384)), "key_version": 1, "session_key_length": 32,
	})
	require.NoError(t, err)

	logData, err := os.ReadFile(auditPath)
	require.NoError(t, err)
	require.NotContains(t, string(logData), sessionKeyB64, "session key in clear in the audit log")
	require.NotContains(t, string(logData), ciphertext, "ciphertext in clear in the audit log")
	found := false
	scanner := bufio.NewScanner(bytes.NewReader(logData))
	scanner.Buffer(make([]byte, 1<<20), 1<<22)
	for scanner.Scan() {
		line := scanner.Text()
		if strings.Contains(line, `"path":"transit/session-key/pkcs1v15/scep-ra-1"`) && strings.Contains(line, `"session_key":"hmac-sha256:`) {
			found = true
		}
	}
	require.True(t, found, fmt.Sprintf("no audit response entry with an HMAC session_key in %d bytes", len(logData)))
}

// Backup and restore keep the opt-in on a key that allows plaintext backup.
func TestTransit_PKCS1v15SessionKey_BackupRestore(t *testing.T) {
	b, s := createBackendWithStorage(t)
	_, err := skWrite(t, b, s, "keys/ra-backup", map[string]any{
		"type": "rsa-3072", "exportable": true, "allow_plaintext_backup": true, "allow_pkcs1v15_session_key": true,
	})
	require.NoError(t, err)
	backup := skRead(t, b, s, "backup/ra-backup").Data["backup"].(string)

	resp, err := skWrite(t, b, s, "restore/ra-restored", map[string]any{"backup": backup})
	require.NoError(t, err)
	require.False(t, resp != nil && resp.IsError())
	require.Equal(t, true, skRead(t, b, s, "keys/ra-restored").Data["allow_pkcs1v15_session_key"])

	want, ciphertext := skEncrypt(t, skPublicKey(t, b, s, "ra-backup", 1), 24)
	resp, err = skUnwrap(t, b, s, "ra-restored", 1, ciphertext, 24)
	requireSessionKey(t, resp, err, want)
}
